import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { CURRENCIES, createMoneyTools, explicitCurrency, formatCompactMoney, formatMoney, formatMoneyInput, normalizeCurrency, parseMoneyInput } from '../src/moneyFormat.js';
import { parseMoneyNumber, roundMoney, storeMoney } from '../src/moneyValue.js';
import { applyTransactionToWallets, replaceTransactionInWallets, moneyNumber, reconcileImportedStatement } from '../src/financeLedger.js';
import { remainingDebtAmount, isOutstandingDebt } from '../src/financialNotifications.js';
