assert.deepEqual(Object.keys(CURRENCIES),['IDR','MYR','SGD','THB','TND']);
assert.equal(normalizeCurrency('USD'),'IDR');
assert.equal(normalizeCurrency('__proto__'),'IDR');
assert.equal(normalizeCurrency(['TND']),'IDR');
assert.equal(formatMoney(1250,'IDR'),'Rp 1.250');
assert.equal(formatMoney(-12.5,'MYR'),'-RM 12.50');
assert.equal(formatMoney(12.5,'SGD'),'S$ 12.50');
assert.equal(formatMoney(12.5,'THB'),'\u0e3f 12.50');
assert.equal(formatMoney(12.345,'TND'),'DT 12,345');
assert.equal(formatMoney(1.234,'TND'),'DT 1,234');
assert.equal(new Intl.NumberFormat('en',{style:'currency',currency:'TND'}).resolvedOptions().maximumFractionDigits,3);
assert.equal(formatMoney(12.345,'TND',{portable:true}),'TND 12,345');
assert.equal(formatMoney(1234.567,'TND',{portable:true}),'TND 1 234,567','PDF grouping must use a supported ASCII space');
for(const code of Object.keys(CURRENCIES)) for(const amount of [0,1,-25,7500,1200000,1250000000,NaN]) {
  const full=formatMoney(amount,code),compact=formatCompactMoney(amount,code);
  assert.ok(full.includes(CURRENCIES[code].symbol));assert.ok(compact.includes(CURRENCIES[code].symbol));
  if(code!=='IDR'){assert.doesNotMatch(full,/Rp/);assert.doesNotMatch(compact,/Rp/);}
}
assert.equal(parseMoneyNumber('1.234'),1234,'Legacy Indonesian grouped strings must remain unchanged');
assert.equal(parseMoneyNumber('1.234,567'),1234.567);
assert.equal(parseMoneyNumber(1.234),1.234);
assert.equal(parseMoneyNumber('12.34'),12.34);
assert.equal(parseMoneyNumber('12,345'),12.345);
assert.equal(parseMoneyInput('1,234.50','MYR'),'1234,50');
assert.equal(parseMoneyInput('12,50','MYR'),'12,50');
assert.equal(parseMoneyInput('12.3459','TND'),'12,345');
assert.equal(parseMoneyInput('1.234.567','MYR'),'1234567');
assert.equal(parseMoneyInput('1.234.567','TND'),'1234567');
assert.equal(formatMoneyInput('12,345','TND'),'12,345');
assert.equal(formatMoneyInput(1.234,'TND'),'1,234');
assert.equal(formatMoneyInput('1000,25','MYR'),'1,000.25');
assert.equal(createMoneyTools('TND').pN('1,234'),1.234);
assert.equal(storeMoney(1.234),1.234,'Fractional values must be numeric, not ambiguous grouped strings');
assert.equal(storeMoney(1234),'1234','Preserve legacy whole-amount strings');
assert.equal(roundMoney(.1+.7+.2),1);
const state={dompet:[{id:'a',saldo:100.123},{id:'b',saldo:5.456}],txs:[],bulan:'November',tahun:'2026'};
const transfer={id:1,tipe:'transfer',dompetId:'a',dompetTo:'b',jml:1.234,biaya:.005};
const moved=applyTransactionToWallets(state.dompet,transfer);
assert.equal(moved[0].saldo,98.884);assert.equal(moved[1].saldo,6.69);
assert.deepEqual(applyTransactionToWallets(moved,transfer,-1),state.dompet);
const revised=replaceTransactionInWallets(moved,transfer,{...transfer,jml:2.345});
assert.equal(revised[0].saldo,97.773);assert.equal(revised[1].saldo,7.801);
const correction=reconcileWalletBalance(state,{walletId:'a',actual:1.234,date:'2026-11-04',today:'2026-11-04',id:2});
assert.equal(correction.state.dompet[0].saldo,1.234);
assert.equal(remainingDebtAmount({jml:1,cicilan:[{jml:.1},{jml:.7},{jml:.2}]}),0);
assert.equal(isOutstandingDebt({jml:1,cicilan:[{jml:.1},{jml:.7},{jml:.2}]}),false);
for(const [code,input,expected] of [['MYR','RM 12.50',12.5],['SGD','S$ 12.50',12.5],['THB','THB 12.50',12.5],['TND','TND 12.345',12.345],['TND','DT 1,234',1.234],['IDR','Rp 12.500',12500]]) assert.equal(parseConversationalMoney(input,code),expected);
