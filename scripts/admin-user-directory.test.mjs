import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { listAdminUsers, invalidateAdminDirectory } from '../api/_lib/adminUserDirectory.js';
import { directoryFixture } from './helpers/admin-directory-fixture.mjs';
const {db,records,usage}=directoryFixture();
const first=await listAdminUsers(db);
assert.equal(first.users.length,8);
assert.equal(usage.reads,9,'Read eight users and one lookahead, not all 1207');
assert.equal(usage.counts,4);
assert.equal(first.stats.total,1207);
assert.equal(first.users[0].data,undefined);
await listAdminUsers(db);
assert.equal(usage.reads,9,'Cache repeat views briefly');
const second=await listAdminUsers(db,{cursor:first.pagination.nextCursor});
assert.equal(usage.reads,18);
assert.equal(usage.counts,4,'Reuse aggregate statistics across pages');
assert.deepEqual(second.users.map(user=>user.uid),records.slice(8,16).map(record=>record.id));
assert.ok((await listAdminUsers(db,{status:'approved'})).users.every(user=>user.approvalStatus==='approved'));
await assert.rejects(listAdminUsers(db,{status:'approved',cursor:first.pagination.nextCursor}),error=>error.status===400);
for(const input of [{limit:999},{q:'a'},{cursor:'bad'},{status:'invalid'},{searchBy:'data'},{cursor:'a'.repeat(4097)}]) await assert.rejects(listAdminUsers(db,input),error=>error.status===400);
const search=directoryFixture(32);
search.records.forEach((record,index)=>{record.value.email=`shared${String(index).padStart(2,'0')}@example.invalid`;record.value.buyerEmail=record.value.email;record.value.displayName=index%2?'BILQIS Test':'Bilqis Test';});
const collect=async input=>{
  const users=[];
  let cursor;
  for(let pages=0;pages<100;pages++) {
    const result=await listAdminUsers(search.db,{...input,...(cursor?{cursor}:{})});
    users.push(...result.users);
    if(!result.pagination.hasMore) return users;
    assert.notEqual(result.pagination.nextCursor,cursor);
    cursor=result.pagination.nextCursor;
  }
  assert.fail('Pagination did not finish');
};
const matches=await collect({q:'shared',searchBy:'email'});
assert.equal(matches.length,32);
assert.equal(new Set(matches.map(user=>user.uid)).size,32,'Deduplicate email/buyer-email across pages');
assert.equal((await collect({q:'bilqis',searchBy:'name'})).length,32);
assert.equal((await collect({q:'shared',searchBy:'email',status:'rejected'})).length,10,'Sparse filtered search must not skip matches');
search.records[5].value.email='different@example.invalid';
invalidateAdminDirectory(search.db);
assert.ok((await collect({q:'shared05',searchBy:'email'})).some(user=>user.uid===search.records[5].id));
search.records[0].value.orderId='ORDER-123';
invalidateAdminDirectory(search.db);
assert.equal((await collect({q:'ORDER-',searchBy:'order'})).length,1);
const collapsed=directoryFixture();
await Promise.all(Array.from({length:10},()=>listAdminUsers(collapsed.db,{refresh:'1'})));
assert.equal(collapsed.usage.queries,1);
assert.equal(collapsed.usage.counts,4);
collapsed.records[0].value.approvalStatus='approved';
invalidateAdminDirectory(collapsed.db);
assert.equal((await listAdminUsers(collapsed.db)).stats.pending_review,402);
const source=readFileSync(new URL('../api/admin/users.js',import.meta.url),'utf8');
assert.ok(source.indexOf('requireAdmin(req)')<source.indexOf('listAdminUsers(db,'),'Authorize before reading cache');
console.log('Admin directory passed: 9 reads instead of 1207, bounded cursors, aggregate counts, cache invalidation, cross-page search, deduplication and authorization');
