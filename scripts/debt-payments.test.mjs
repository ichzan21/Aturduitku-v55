import assert from 'node:assert/strict';
import { isDebtPayment, reverseDebtPayment } from '../src/debtPayments.js';
import { remainingDebtAmount, isOutstandingDebt } from '../src/financialNotifications.js';
import { applyTransactionToWallets } from '../src/financeLedger.js';

const date='2026-10-20';
const payment={id:'pay',debtId:7,tipe:'pengeluaran',tgl:date,jml:'60000',dompetId:'cash',ket:'Bayar Utang/Cicilan: Utang QA'};
const debt={id:7,tipe:'utang',nama:'Utang QA',jml:'100000',lunas:true,status:'LUNAS',cicilan:[{txId:'first',tgl:date,jml:'40000'},{txId:'pay',tgl:date,jml:'60000'}]};
const state={utang:[debt],goals:[],dompet:[{id:'cash',saldo:'400000'},{id:'other',saldo:'11'}],txs:[payment]};
const before=JSON.stringify(state);
const reversed=reverseDebtPayment(state,payment);
assert.equal(remainingDebtAmount(reversed.utang[0]),60000);
assert.equal(isOutstandingDebt(reversed.utang[0]),true);
assert.equal(reversed.utang[0].status,'aktif');
assert.equal(reversed.utang[0].cicilan.length,1);
assert.equal(JSON.stringify(state),before,'Reversal must not mutate the original snapshot used for Undo');
assert.deepEqual(applyTransactionToWallets(state.dompet,payment,-1).map(w=>w.saldo),['460000','11']);
assert.equal(reverseDebtPayment(state,{...payment,debtId:'7'}).utang[0].lunas,false);
assert.equal(isDebtPayment({...payment,tipe:'piutang_keluar'}),false,'Lending is not an installment payment');
assert.equal(isDebtPayment({tipe:'pengeluaran',ket:'Bayar listrik'}),false);
assert.equal(reverseDebtPayment(state,{tipe:'pengeluaran',ket:'Bayar listrik'}).utang,state.utang);

const legacyTx={id:'old',tipe:'pengeluaran',tgl:date,jml:'20.000',dompetId:'cash',ket:'Bayar Utang/Cicilan: Utang Lama',displayName:'Nama tampilan baru'};
const legacyDebt={id:'legacy',tipe:'utang',nama:'Utang Lama',jml:'50000',lunas:false,cicilan:[{tgl:date,jml:'20000'}]};
const legacy={...state,utang:[legacyDebt],txs:[legacyTx]};
assert.equal(remainingDebtAmount(reverseDebtPayment(legacy,legacyTx).utang[0]),50000);
const aiLegacy={...legacyTx,ket:'Bayar utang: Utang Lama'};
assert.equal(reverseDebtPayment({...legacy,txs:[aiLegacy]},aiLegacy).utang[0].cicilan.length,0);
assert.throws(()=>reverseDebtPayment({...legacy,utang:[{...legacyDebt,cicilan:[...legacyDebt.cicilan,...legacyDebt.cicilan]}]},legacyTx),{code:'DEBT_PAYMENT_UNRESOLVED'});
assert.throws(()=>reverseDebtPayment({...legacy,txs:[legacyTx,{...legacyTx,id:'competing'}]},legacyTx),{code:'DEBT_PAYMENT_UNRESOLVED'});
assert.throws(()=>reverseDebtPayment({...legacy,utang:[legacyDebt,{...legacyDebt,id:'duplicate'}]},legacyTx),{code:'DEBT_PAYMENT_UNRESOLVED'});
assert.throws(()=>reverseDebtPayment({...legacy,utang:[{...legacyDebt,cicilan:[{...legacyDebt.cicilan[0],txId:'different'}]}]},legacyTx),{code:'DEBT_PAYMENT_UNRESOLVED'});
assert.throws(()=>reverseDebtPayment({...legacy,utang:[{...legacyDebt,cicilan:[{...legacyDebt.cicilan[0],dompetId:'other'}]}]},legacyTx),{code:'DEBT_PAYMENT_UNRESOLVED'});
assert.throws(()=>reverseDebtPayment({...legacy,utang:[{...legacyDebt,cicilan:[{...legacyDebt.cicilan[0],tgl:'2026-10-19'}]}]},legacyTx),{code:'DEBT_PAYMENT_UNRESOLVED'});

const incoming={...payment,tipe:'piutang_masuk',piutangId:7,ket:'Terima Piutang/Cicilan: Utang QA'};
assert.equal(reverseDebtPayment({...state,utang:[{...debt,tipe:'piutang'}],txs:[incoming]},incoming).utang[0].lunas,false);
assert.equal(applyTransactionToWallets(state.dompet,incoming,-1)[0].saldo,'340000');
const goalTx={...incoming,tipe:'piutang_masuk_goal',goalId:'goal',dompetId:''};
const goal={id:'goal',kumpul:'160000',history:[{txId:'unrelated',jml:'100000'},{txId:'pay',tgl:date,jml:'60000',tipe:'pengembalian_piutang'}]};
const goalState={...state,utang:[{...debt,tipe:'piutangBisnis'}],txs:[goalTx],goals:[goal]};
const goalBefore=JSON.stringify(goalState);
const goalReversal=reverseDebtPayment(goalState,goalTx);
assert.equal(goalReversal.goals[0].kumpul,'100000');
assert.deepEqual(goalReversal.goals[0].history,[goal.history[0]]);
assert.equal(remainingDebtAmount(goalReversal.utang[0]),60000);
assert.deepEqual(applyTransactionToWallets(state.dompet,goalTx,-1),state.dompet);
assert.equal(reverseDebtPayment({...goalState,utang:[]},goalTx).goals[0].kumpul,'100000','Goal rollback also works after the separate debt record was removed');
assert.throws(()=>reverseDebtPayment({...goalState,goals:[{...goal,kumpul:'1000'}]},goalTx),{code:'DEBT_GOAL_FUNDS_UNAVAILABLE'});
assert.throws(()=>reverseDebtPayment({...goalState,goals:[{...goal,history:[]}]},goalTx),{code:'DEBT_PAYMENT_UNRESOLVED'});
assert.equal(JSON.stringify(goalState),goalBefore);
console.log('Debt payment rollback tests passed: linked and unique legacy records, partial/full settlement, Goal reversal, ambiguity rejection and immutable Undo snapshots');
